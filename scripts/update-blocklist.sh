#!/usr/bin/env bash
# Refresh AdBlock's own bundled data. Run from the repository root.
# StevenBlack unified hosts (MIT); HaGeZi PRO, Pop-Up Ads and TIF Medium (GPL-3.0).
# TIF Medium adds known threat domains while keeping mobile memory use bounded.
set -euo pipefail
OUT="systemblock/src/main/assets/blocklist.txt.gz"
BLOCK_TMP="$(mktemp -d)"
trap 'rm -rf "$BLOCK_TMP"' EXIT
curl -fsSL --connect-timeout 20 --max-time 180 --retry 3 https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts -o "$BLOCK_TMP/stevenblack"
for list in pro popupads tif.medium; do
  curl -fsSL --connect-timeout 20 --max-time 180 --retry 3 "https://raw.githubusercontent.com/hagezi/dns-blocklists/main/wildcard/$list-onlydomains.txt" -o "$BLOCK_TMP/$list"
done
python3 - "$BLOCK_TMP" "$OUT" <<'PY'
from pathlib import Path
import gzip, hashlib, json, os, re, sys
from datetime import datetime, timezone
folder, output = map(Path, sys.argv[1:])
valid = re.compile(r'(?=.{1,253}$)[a-z0-9_](?:[a-z0-9_-]*[a-z0-9_])?(?:\.[a-z0-9_](?:[a-z0-9_-]*[a-z0-9_])?)+\Z')
sources = [
 ('stevenblack', 'StevenBlack unified hosts', 'MIT', 10000),
 ('pro', 'HaGeZi Multi PRO', 'GPL-3.0', 50000),
 ('popupads', 'HaGeZi Pop-Up Ads', 'GPL-3.0', 10000),
 ('tif.medium', 'HaGeZi Threat Intelligence Feeds Medium', 'GPL-3.0', 100000),
]
merged, metadata = set(), []
for name, title, licence, minimum in sources:
 raw = (folder/name).read_bytes(); lines = raw.decode('utf-8').splitlines(); domains = set()
 for line in lines:
  if name == 'stevenblack':
   fields = line.split('#',1)[0].split()
   candidates = fields[1:] if fields and fields[0] in ('0.0.0.0','127.0.0.1') else []
  else: candidates = [] if line.startswith('#') else [line.strip()]
  domains.update(d.lower() for d in candidates if valid.fullmatch(d.lower()))
 if len(domains) < minimum: raise SystemExit(f'{name}: only {len(domains)} valid domains; refusing to replace bundle')
 version = next((l.split(':',1)[1].strip() for l in lines if l.startswith('# Version:')), 'see source snapshot hash')
 url = 'https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts' if name == 'stevenblack' else f'https://raw.githubusercontent.com/hagezi/dns-blocklists/main/wildcard/{name}-onlydomains.txt'
 metadata.append(dict(name=title,license=licence,url=url,version=version,sha256=hashlib.sha256(raw).hexdigest(),parsed_domains=len(domains)))
 merged.update(domains)
def has_parent(domain):
 labels = domain.split('.')
 return any('.'.join(labels[i:]) in merged for i in range(1,len(labels)))
final = sorted(d for d in merged if not has_parent(d))
if len(final) < 400000: raise SystemExit(f'Only {len(final)} distinct parent rules; refusing an unexpectedly small refresh')
for host in ['example.com','cloudflare-dns.com','github.com','google.com','microsoft.com','apple.com']:
 if host in merged or has_parent(host): raise SystemExit(f'Critical connectivity domain unexpectedly blocked: {host}')
output.parent.mkdir(parents=True,exist_ok=True)
header = ['# AdBlock bundled domain rules — generated by scripts/update-blocklist.sh', '# Sources:']
header += [f"#   {s['name']} ({s['license']}), {s['url']}, version {s['version']}" for s in metadata]
header += [f'# Domains: {len(final)} (each also blocks its subdomains)', '# Includes ad, tracker, pop-up and known-threat domains; not a count of ads removed.']
temporary = output.with_suffix('.tmp')
temporary.write_bytes(gzip.compress(('\n'.join(header+final)+'\n').encode('utf-8'),mtime=0));os.replace(temporary,output)
manifest=dict(generated_utc=datetime.now(timezone.utc).isoformat(),domain_count=len(final),sources=metadata)
output.with_name('blocklist-sources.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps({'domains':len(final),'bytes':output.stat().st_size,'sources':[{s['name']:s['parsed_domains']} for s in metadata]}))
PY
